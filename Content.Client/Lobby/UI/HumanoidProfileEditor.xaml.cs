    /// <summary>
    /// Refreshes traits selector
    /// </summary>
    public void RefreshTraits()
    {
        TraitsList.RemoveAllChildren();

        var traits = _prototypeManager.EnumeratePrototypes<TraitPrototype>()
            .OrderBy(t => t.Cost)
            .ThenBy(t => Loc.GetString(t.Name))
            .ToList();
        TabContainer.SetTabTitle(3, Loc.GetString("humanoid-profile-editor-traits-tab"));

        if (traits.Count < 1)
        {
            TraitsList.AddChild(new Label
            {
                Text = Loc.GetString("humanoid-profile-editor-no-traits"),
                FontColorOverride = Color.Gray,
            });
            return;
        }

        // Claw Command - build lookup of department jobs for restriction checks.
        var deptJobs = new Dictionary<string, HashSet<string>>();
        var deptNames = new Dictionary<string, string>();
        foreach (var dept in _prototypeManager.EnumeratePrototypes<DepartmentPrototype>())
        {
            var jobs = new HashSet<string>();
            foreach (var role in dept.Roles)
                jobs.Add(role.Id);
            deptJobs[dept.ID] = jobs;
            deptNames[dept.ID] = Loc.GetString(dept.Name);
        }

        // Claw Command - determine which traits are dept-blocked based on current job prefs.
        bool IsTraitDeptBlocked(TraitPrototype trait, out string blockedDeptName)
        {
            blockedDeptName = "";
            if (trait.RestrictedDepts.Count == 0 || Profile == null)
                return false;

            foreach (var deptId in trait.RestrictedDepts)
            {
                if (!deptJobs.TryGetValue(deptId, out var roles))
                    continue;

                foreach (var (jobId, pri) in Profile.JobPriorities)
                {
                    if (pri > JobPriority.Never && roles.Contains(jobId))
                    {
                        blockedDeptName = deptNames.GetValueOrDefault(deptId, deptId);
                        return true;
                    }
                }
            }
            return false;
        }

        // Claw Command - determine if a trait is restricted to a species the player hasn't selected.
        bool IsTraitSpeciesBlocked(TraitPrototype trait)
        {
            if (trait.RestrictedSpecies.Count == 0 || Profile == null)
                return false;

            return !trait.RestrictedSpecies.Contains(Profile.Species);
        }

        // Claw Command - determine if a trait is excluded by any currently selected trait.
        bool IsTraitExcluded(TraitPrototype trait, out string conflictName)
        {
            conflictName = "";
            if (trait.Excludes.Count == 0 || Profile == null)
                return false;

            foreach (var ex in trait.Excludes)
            {
                if (Profile.TraitPreferences.Contains(ex))
                {
                    if (_prototypeManager.TryIndex<TraitPrototype>(ex, out var exProto))
                        conflictName = Loc.GetString(exProto.Name);
                    return true;
                }
            }
            return false;
        }

        // Claw Command - strip any currently selected traits that are now invalid due to job or species changes.
        if (Profile != null)
        {
            var toRemove = new List<string>();
            foreach (var selectedTrait in Profile.TraitPreferences)
            {
                if (!_prototypeManager.TryIndex<TraitPrototype>(selectedTrait, out var selProto))
                    continue;

                if (IsTraitDeptBlocked(selProto, out _) || IsTraitSpeciesBlocked(selProto))
                    toRemove.Add(selectedTrait);
            }

            foreach (var id in toRemove)
            {
                Profile = Profile?.WithoutTraitPreference(id, _prototypeManager);
            }

            if (toRemove.Count > 0)
                SetDirty();
        }

        // Setup model
        Dictionary<string, List<string>> traitGroups = new();
        List<string> defaultTraits = new();
        traitGroups.Add(TraitCategoryPrototype.Default, defaultTraits);

        foreach (var trait in traits)
        {
            // Claw Command - skip species-restricted traits that don't match the current species.
            if (IsTraitSpeciesBlocked(trait))
                continue;

            if (trait.Category == null)
            {
                defaultTraits.Add(trait.ID);
                continue;
            }

            if (!_prototypeManager.HasIndex(trait.Category))
                continue;

            var group = traitGroups.GetOrNew(trait.Category);
            group.Add(trait.ID);
        }

        // Claw Command - pre-calculate shared budget pool totals across all categories
        Dictionary<string, int> poolTotals = new();
        Dictionary<string, int?> poolLimits = new();

        foreach (var (categoryId, categoryTraits) in traitGroups)
        {
            if (categoryId == TraitCategoryPrototype.Default)
                continue;

            var cat = _prototypeManager.Index<TraitCategoryPrototype>(categoryId);
            var poolKey = cat.BudgetPool ?? cat.ID;

            // Resolve max points for this pool (first category that defines it wins)
            if (!poolLimits.ContainsKey(poolKey))
                poolLimits[poolKey] = cat.MaxTraitPoints;
            else if (poolLimits[poolKey] == null && cat.MaxTraitPoints.HasValue)
                poolLimits[poolKey] = cat.MaxTraitPoints;

            foreach (var traitId in categoryTraits)
            {
                var trait = _prototypeManager.Index<TraitPrototype>(traitId);
                if (Profile?.TraitPreferences.Contains(trait.ID) == true)
                {
                    poolTotals[poolKey] = poolTotals.GetValueOrDefault(poolKey) + trait.Cost;
                }
            }
        }

        // Show the shared budget pool counter at the top
        var sharedPoolKey = "SharedTraitBudget";
        if (poolLimits.TryGetValue(sharedPoolKey, out var sharedLimit) && sharedLimit is >= 0)
        {
            var sharedSpent = poolTotals.GetValueOrDefault(sharedPoolKey);
            TraitsList.AddChild(new Label
            {
                Text = Loc.GetString("humanoid-profile-editor-trait-count-hint",
                    ("current", sharedSpent),
                    ("max", sharedLimit)),
                StyleClasses = { StyleClass.LabelHeading },
                Margin = new Thickness(0, 0, 0, 5),
            });
        }

        // Track whether we've already shown the counter label for a BudgetPool
        HashSet<string> shownPoolCounters = new() { sharedPoolKey };

        // Create UI view from model
        foreach (var (categoryId, categoryTraits) in traitGroups)
        {
            TraitCategoryPrototype? category = null;
            string? poolKey = null;
            int? poolLimit = null;
            var spent = 0;

            if (categoryId != TraitCategoryPrototype.Default)
            {
                category = _prototypeManager.Index<TraitCategoryPrototype>(categoryId);
                poolKey = category.BudgetPool ?? category.ID;
                poolLimit = poolLimits.GetValueOrDefault(poolKey);
                spent = poolTotals.GetValueOrDefault(poolKey);

                // Label
                TraitsList.AddChild(new Label
                {
                    Text = Loc.GetString(category.Name),
                    Margin = new Thickness(0, 10, 0, 0),
                    StyleClasses = { StyleClass.LabelHeading },
                });
            }

            List<(TraitPreferenceSelector selector, TraitPrototype proto)> selectors = new();

            foreach (var traitProto in categoryTraits)
            {
                var trait = _prototypeManager.Index<TraitPrototype>(traitProto);
                var selector = new TraitPreferenceSelector(trait);

                selector.Preference = Profile?.TraitPreferences.Contains(trait.ID) == true;

                selector.PreferenceChanged += preference =>
                {
                    if (preference)
                    {
                        Profile = Profile?.WithTraitPreference(trait.ID, _prototypeManager);
                    }
                    else
                    {
                        Profile = Profile?.WithoutTraitPreference(trait.ID, _prototypeManager);
                    }

                    SetDirty();
                    RefreshTraits(); // If too many traits are selected, they will be reset to the real value.
                };
                selectors.Add((selector, trait));
            }

            // Selection counter - show once per BudgetPool
            if (poolKey != null && poolLimit is >= 0 && shownPoolCounters.Add(poolKey))
            {
                TraitsList.AddChild(new Label
                {
                    Text = Loc.GetString("humanoid-profile-editor-trait-count-hint",
                        ("current", spent),
                        ("max", poolLimit)),
                    FontColorOverride = Color.Gray
                });
            }

            foreach (var (selector, proto) in selectors)
            {
                // Claw Command - check department restrictions.
                if (IsTraitDeptBlocked(proto, out var blockedDept))
                {
                    selector.Checkbox.Disabled = true;
                    selector.Preference = false;
                    selector.Checkbox.Label.FontColorOverride = Color.Gray;
                    var tip = selector.Checkbox.ToolTip ?? "";
                    selector.Checkbox.ToolTip = tip + "\n" +
                        Loc.GetString("trait-restricted-dept-hint", ("department", blockedDept));
                }
                // Claw Command - check mutual exclusions.
                else if (IsTraitExcluded(proto, out var conflictTrait))
                {
                    selector.Checkbox.Disabled = true;
                    selector.Preference = false;
                    selector.Checkbox.Label.FontColorOverride = Color.Gray;
                    var tip = selector.Checkbox.ToolTip ?? "";
                    selector.Checkbox.ToolTip = tip + "\n" +
                        Loc.GetString("trait-excluded-hint", ("trait", conflictTrait));
                }
                // Budget overflow check.
                else if (poolLimit is >= 0 &&
                    selector.Cost + spent > poolLimit)
                {
                    selector.Checkbox.Label.FontColorOverride = Color.Red;
                }

                TraitsList.AddChild(selector);
            }
        }
    }

    /// <summary>
    /// Refreshes the species selector.
    /// </summary>
    public void RefreshSpecies()
    {
        SpeciesButton.Clear();
        _species.Clear();

        _species.AddRange(_prototypeManager.EnumeratePrototypes<SpeciesPrototype>().Where(o => o.RoundStart));
        _species.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));
        var speciesIds = _species.Select(o => o.ID).ToList();

        for (var i = 0; i < _species.Count; i++)
        {
            var name = Loc.GetString(_species[i].Name);
            SpeciesButton.AddItem(name, i);

            if (Profile?.Species.Equals(_species[i].ID) == true)
            {
                SpeciesButton.SelectId(i);
            }
        }

        // If our species isn't available then reset it to default.
        if (Profile != null)
        {
            if (!speciesIds.Contains(Profile.Species))
            {
                SetSpecies(HumanoidCharacterProfile.DefaultSpecies);
            }
        }
    }

    public void RefreshAntags()
    {
        AntagList.RemoveAllChildren();
        var items = new[]
        {
            ("humanoid-profile-editor-antag-preference-yes-button", 0),
            ("humanoid-profile-editor-antag-preference-no-button", 1)
        };

        foreach (var antag in _prototypeManager.EnumeratePrototypes<AntagPrototype>()
                     .OrderBy(a => Loc.GetString(a.Name)))
        {
            if (!antag.SetPreference)
                continue;

            var antagContainer = new BoxContainer()
            {
                Orientation = LayoutOrientation.Horizontal,
            };

            var selector = new RequirementsSelector()
            {
                Margin = new Thickness(3f, 3f, 3f, 0f),
            };
            selector.OnOpenGuidebook += OnOpenGuidebook;

            var title = Loc.GetString(antag.Name);
            var description = Loc.GetString(antag.Objective);
            selector.Setup(items, title, 250, description, guides: antag.Guides);
            selector.Select(Profile?.AntagPreferences.Contains(antag.ID) == true ? 0 : 1);

            if (!_requirements.IsAllowed(
                    antag,
                    (HumanoidCharacterProfile?)_preferencesManager.Preferences?.SelectedCharacter,
                    out var reason))
            {
                selector.LockRequirements(reason);
                Profile = Profile?.WithAntagPreference(antag.ID, false);
                SetDirty();
            }
            else
            {
                selector.UnlockRequirements();
            }

            selector.OnSelected += preference =>
            {
                Profile = Profile?.WithAntagPreference(antag.ID, preference == 0);
                SetDirty();
            };

            antagContainer.AddChild(selector);

            antagContainer.AddChild(new Button()
            {
                Disabled = true,
                Text = Loc.GetString("loadout-window"),
                HorizontalAlignment = HAlignment.Right,
                Margin = new Thickness(3f, 0f, 0f, 0f),
            });

            AntagList.AddChild(antagContainer);
        }
    }

    private void SetDirty()
    {
        // If it equals default then reset the button.
        if (Profile == null || _preferencesManager.Preferences?.SelectedCharacter.MemberwiseEquals(Profile) == true)
        {
            IsDirty = false;
            return;
        }

        // TODO: Check if profile matches default.
        IsDirty = true;
    }

